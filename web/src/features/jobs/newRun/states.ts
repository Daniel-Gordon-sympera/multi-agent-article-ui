const BY_CODE = new Map(US_STATES.map((state) => [state.code, state]));
const BY_NAME = new Map(US_STATES.map((state) => [state.name.toLowerCase(), state]));

/** "fl" · "Florida" → "FL"; unknown input is returned upper-cased as typed. */
export function stateCodeOf(value: string | null | undefined): string {
  const text = (value ?? "").trim();
  if (!text) return "";
  const byCode = BY_CODE.get(text.toUpperCase());
  if (byCode) return byCode.code;
  return BY_NAME.get(text.toLowerCase())?.code ?? text.toUpperCase();
}

export function stateLabel(code: string): string {
  const state = BY_CODE.get(code.toUpperCase());
  return state ? `${state.name} (${state.code})` : code;
}
